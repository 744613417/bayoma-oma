% 运行全部校核脚本。
%
% 每个脚本独立运行，失败不中断后续脚本。运行：
%   matlab -batch "addpath(genpath(fullfile(fileparts(mfilename('fullpath')), '..'))); cd('matlab/tests'); run_all"

here = fileparts(mfilename('fullpath'));
cd(here);

scripts = { ...
    'test_single_mode', ...
    'test_total_entry', ...
    'test_select_bands', ...
    'test_multi_mode', ...
    'test_multi_setup', ...
    'test_condense', ...
    'test_multi_setup_cov', ...
    'test_asynchronous', ...
    'test_asynchronous_multi', ...
    'test_uncertainty_matrix', ...
    'test_io_json', ...
    'test_results', ...
    'test_cov_cross', ...
    'test_py_case'};

failed = {};
for k = 1:numel(scripts)
    fprintf('\n===== %s =====\n', scripts{k});
    try
        feval(scripts{k});
    catch err
        fprintf('失败：%s\n', err.message);
        failed{end+1} = scripts{k}; %#ok<AGROW>
    end
end

fprintf('\n===== 汇总 =====\n');
if isempty(failed)
    fprintf('全部 %d 个脚本通过\n', numel(scripts));
else
    fprintf('失败 %d 个：%s\n', numel(failed), strjoin(failed, ', '));
end
