    function check(ok, label, detail)
        %CHECK Record one assertion and print its verdict.
        ok = logical(ok);
        nPass = nPass + ok;
        nFail = nFail + ~ok;
        if isempty(detail)
            fprintf('%s %s\n', ternary(ok, '[OK ]', '[FAIL]'), label);
        else
            fprintf('%s %s  %s\n', ternary(ok, '[OK ]', '[FAIL]'), label, detail);
        end
    end
end

