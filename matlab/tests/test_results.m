function write_spec(path, spec)
%WRITE_SPEC Write the job description as UTF-8 JSON.
fid = fopen(path, 'w', 'n', 'UTF-8');
if fid < 0
    error('bayoma:writeFail', 'cannot write %s', path);
end
fprintf(fid, '%s', jsonencode(spec));
fclose(fid);
end

% ----------------------------------------------------------------------
function out = ternary(cond, a, b)
%TERNARY Conditional expression.
if cond
    out = a;
else
    out = b;
end
end

% ----------------------------------------------------------------------
function tdata = synth_async(f, z, S, Se, phi, Vc, groups, fs, dur, seed)
%SYNTH_ASYNC Synthesise data that follow the asynchronous spectral model.
%
%   The scaled FFT of the data has covariance E_k, while the FFT itself has
%   covariance E_k * nt / dt; samples are drawn with that covariance, the
%   negative frequency half is filled by conjugate symmetry and the records
%   are recovered by the inverse transform.
nch = size(phi, 1);
m = numel(f);
ng = numel(groups);
nt = round(dur * fs);
dt = 1 / fs;
nf = floor(nt / 2) + 1;
freqs = (0:nf - 1).' * fs / nt;

h = bayoma.transfer_matrix(f(:), z(:), freqs, 0);
h(:, 1) = 0;                 % the DC bin is singular for q = 0
d0 = zeros(nch, 1);
for r = 1:ng
    d0(groups{r}) = Se(r);
end
U = cell(1, m);
for i = 1:m
    Ui = zeros(nch, ng);
    for r = 1:ng
        Ui(groups{r}, r) = phi(groups{r}, i);
    end
    U{i} = Ui;
end
S = (S + S') / 2;
D0 = diag(d0);

rng(seed);
spec = complex(zeros(nf, nch));
% 相干矩阵既可能按测组对给成元胞（每项一个 ng x ng 矩阵），也可能直接给成
% 一个 ng x ng 矩阵；这里统一取成元胞再索引，避免对数值矩阵用花括号索引时
% 取到单个元素而使矩阵乘法维度不符。
if ~iscell(Vc)
    VcMat = Vc;
    Vc = cell(m, m);
    for i = 1:m
        for j = 1:m
            Vc{i, j} = VcMat;
        end
    end
end
for k = 1:nf
    Ek = D0;
    for i = 1:m
        for j = 1:m
            c = S(i, j) * h(i, k) * conj(h(j, k));
            if c ~= 0
                Ek = Ek + c * (U{i} * Vc{i, j} * U{j}.');
            end
        end
    end
    Ek = (Ek + Ek') / 2;
    [Ve, De] = eig(Ek);
    dv = max(real(diag(De)), 0);
    root = Ve * diag(sqrt(dv * nt / dt));
    w = (randn(nch, 1) + 1i * randn(nch, 1)) / sqrt(2);
    spec(k, :) = (root * w).';
end
full = [spec; conj(spec(end - 1:-1:2, :))];
tdata = real(ifft(full, [], 1));
end
